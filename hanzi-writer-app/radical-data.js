// Build reverse lookup: char → radical key
var CHAR_RADICAL = {};
Object.keys(RADICAL_MAP).forEach(function(key) {
    var chars = RADICAL_MAP[key].c;
    for (var i = 0; i < chars.length; i++) {
        CHAR_RADICAL[chars[i]] = key;
    }
});

// Get radical info for a character
function getRadicalInfo(char) {
    var key = CHAR_RADICAL[char];
    if (!key) return null;
    var info = RADICAL_MAP[key];
    return { key: key, radical: info.r, name: info.n, strokes: info.s };
}

// Get related characters with same radical (up to max)
function getRelatedByRadical(char, max) {
    var key = CHAR_RADICAL[char];
    if (!key) return [];
    var chars = RADICAL_MAP[key].c;
    var result = [];
    for (var i = 0; i < chars.length && result.length < (max || 12); i++) {
        if (chars[i] !== char) result.push(chars[i]);
    }
    return result;
}
